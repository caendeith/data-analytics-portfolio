@dataclass(frozen=True)
class Review:
    """Один отзыв с gold-меткой."""

    id: str
    marketplace: str
    product: str
    product_category: str
    rating: int
    text: str
    gold_label: str


def allocate_counts(total: int, weights: dict[str, float]) -> dict[str, int]:
    """Разложить `total` по весам методом наибольших остатков.

    Гарантирует, что сумма ровно `total`, и что результат детерминирован:
    при равных остатках порядок берётся из LABELS.
    """
    raw = {k: total * w for k, w in weights.items()}
    base = {k: int(v) for k, v in raw.items()}
    missing = total - sum(base.values())
    # Порядок при равных остатках — по порядку классов в LABELS, чтобы результат
    # не зависел от случайности. Метки вне LABELS (например, в тестах) уходят в конец.
    order = sorted(
        raw,
        key=lambda k: (-(raw[k] - base[k]), LABELS.index(k) if k in LABELS else len(LABELS)),
    )
    for key in order[:missing]:
        base[key] += 1
    return base


def _introduce_typo(text: str, rng: Random) -> str:
    """Одна правдоподобная опечатка в случайном длинном слове."""
    words = [(m.start(), m.end(), m.group()) for m in re.finditer(r"[а-яё]{6,}", text)]
    if not words:
        return text
    start, end, word = rng.choice(words)
    mode = rng.choice(("dup", "drop", "swap"))
    if mode == "dup":
        idxs = [i for i, ch in enumerate(word) if ch in "бвгджзклмнпрстфхцчшщ" and 1 <= i < len(word) - 1]
        if not idxs:
            return text
        i = rng.choice(idxs)
        broken = word[:i] + word[i] + word[i:]
    elif mode == "drop":
        idxs = [i for i, ch in enumerate(word) if ch in "аеёиоуыэюя" and 1 <= i < len(word) - 1]
        if not idxs:
            return text
        i = rng.choice(idxs)
        broken = word[:i] + word[i + 1:]
    else:
        i = rng.randrange(1, len(word) - 1)
        broken = word[:i] + word[i + 1] + word[i] + word[i + 2:]
    return text[:start] + broken + text[end:]


def _wrap_with_emoji(text: str, rng: Random) -> str:
    if rng.random() > 0.32:
        return text
    emoji = rng.choice(_EMOJI)
    if rng.random() < 0.5 and len(text) > 24:
        cut = text.find(". ", 10)
        if cut != -1:
            return text[: cut + 2] + emoji + " " + text[cut + 2:]
    return text + " " + emoji


def _pick_product(label: str, rng: Random) -> tuple[str, str]:
    if label == "размер":
        pool = [p for p in PRODUCTS if p[1] in _SIZE_PRODUCT_CATS]
    else:
        pool = list(PRODUCTS)
    # повторяемость: rng уже seeded, choice детерминирован
    return pool[rng.randrange(len(pool))]


def _render(label: str, rng: Random) -> tuple[str, str, str]:
    product, category = _pick_product(label, rng)
    template = TEMPLATES[label][rng.randrange(len(TEMPLATES[label]))]
    size = _SIZES[rng.randrange(len(_SIZES))]
    text = template.format(
        p=product,
        size=size,
        size_alt=_SIZE_DOWN[size],
        days=rng.choice((4, 5, 7, 9, 12)),
        num=f"{rng.randrange(100000, 999999)}",
    )
    if label != "нет_жалобы":
        if rng.random() < 0.28:
            text = _OPENERS[rng.randrange(len(_OPENERS))].format(num=f"{rng.randrange(100000, 999999)}") + text
        if rng.random() < 0.28:
            text += _CLOSERS[rng.randrange(len(_CLOSERS))]
    if rng.random() < 0.24:
        text = _introduce_typo(text, rng)
    text = _wrap_with_emoji(text, rng)
    if rng.random() < 0.30:
        text = text[0].upper() + text[1:] if text else text
    return text, product, category


def _rating(label: str, rng: Random) -> int:
    if label == "нет_жалобы":
        return rng.choices((3, 4, 5), weights=(0.12, 0.43, 0.45))[0]
    return rng.choices((1, 2, 3), weights=(0.42, 0.36, 0.22))[0]


def generate_reviews(seed: int = SEED, n: int = N_REVIEWS) -> list[Review]:
    """Сгенерировать `n` отзывов. Детерминированно от `seed` и `n`."""
    if n <= 0:
        raise ValueError("n должно быть > 0")
    rng = Random(seed)
    counts = allocate_counts(n, CLASS_WEIGHTS)
    labels: list[str] = []
    for label in LABELS:
        labels.extend([label] * counts[label])
    # перемешиваем: классы не идут блоками
    for i in range(len(labels) - 1, 0, -1):
        j = rng.randrange(i + 1)
        labels[i], labels[j] = labels[j], labels[i]

    reviews: list[Review] = []
    for i, label in enumerate(labels, start=1):
        text, product, category = _render(label, rng)
        marketplace = MARKETPLACES[0] if rng.random() < 0.62 else MARKETPLACES[1]
        reviews.append(
            Review(
                id=f"r{i:04d}",
                marketplace=marketplace,
                product=product,
                product_category=category,
                rating=_rating(label, rng),
                text=text,
                gold_label=label,
            )
        )
    return reviews


def class_distribution(reviews: Iterable[Review]) -> dict[str, int]:
    """Счётчик gold-меток в том же порядке, что LABELS."""
    dist = {label: 0 for label in LABELS}
    for review in reviews:
        dist[review.gold_label] += 1
    return dist
